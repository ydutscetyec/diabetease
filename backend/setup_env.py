"""One-time setup: creates backend/.env with a generated key and an admin account.

    python setup_env.py

Re-running will not overwrite an existing .env unless --force is passed.
"""
from __future__ import annotations

import getpass
import secrets
import sys
from pathlib import Path

from app.security import hash_password

HERE = Path(__file__).resolve().parent
ENV = HERE / ".env"

TEMPLATE = """# Generated by setup_env.py. Do not commit this file.

DATABASE_URL=sqlite:///./diabetease.db

SECRET_KEY={secret}
ADMIN_USERNAME={admin}
ADMIN_PASSWORD_HASH={pwhash}

CORS_ORIGINS=
RATE_LIMIT_PER_MINUTE=60
SERVE_FRONTEND=true

# Assessments are discarded unless this is true AND the respondent consents.
# Do not enable without ethics clearance.
STORE_ASSESSMENTS=false
ASSESSMENT_RETENTION_DAYS=90

MODEL_PATH=./ml/artifacts/model.joblib

# Optional: connect a language model so the assistant can answer open questions.
# Ollama example:
#   LLM_BASE_URL=http://localhost:11434/v1
#   LLM_MODEL=llama3.2
#   LLM_API_KEY=ollama
LLM_BASE_URL=
LLM_MODEL=
LLM_API_KEY=
"""


def main() -> None:
    if ENV.exists() and "--force" not in sys.argv:
        print(f"{ENV} already exists. Pass --force to regenerate it.")
        print("Regenerating changes SECRET_KEY, which signs out every existing session.")
        return

    print("DiabetEASE setup\n")
    admin = input("Admin username [admin]: ").strip() or "admin"

    while True:
        pw = getpass.getpass("Admin password (min 10 characters): ")
        if len(pw) < 10:
            print("  Too short. Use at least 10 characters.\n")
            continue
        if pw != getpass.getpass("Confirm password: "):
            print("  Passwords did not match.\n")
            continue
        break

    ENV.write_text(TEMPLATE.format(
        secret=secrets.token_hex(32), admin=admin, pwhash=hash_password(pw)
    ))
    print(f"\nWrote {ENV}")
    print("  SECRET_KEY generated (64 hex characters)")
    print(f"  Admin account: {admin} (role: admin)")
    print("\nNext:")
    print("  python seed.py")
    print("  python import_facilities.py facilities_google_candidates.csv --commit")
    print("  python -m uvicorn app.main:app --reload --port 8000")


if __name__ == "__main__":
    main()
