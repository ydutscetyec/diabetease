"""Generate clearly labelled synthetic records for SOFTWARE TESTING ONLY.

These rows are not patients. They are not South Cotabato data. They exist so the
training pipeline and the inference endpoint can be exercised before a real
dataset is secured. The manifest written alongside the CSV marks them synthetic,
and train.py refuses to activate any model trained from a synthetic manifest.
"""
from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent


def generate(n: int, seed: int) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    label = rng.binomial(1, 0.25, n)
    df = pd.DataFrame({
        "age": rng.integers(2, 40, n),
        "family_history_t1d": rng.binomial(1, np.where(label == 1, 0.18, 0.05)),
        "n_symptoms": rng.binomial(6, np.where(label == 1, 0.55, 0.08)),
        "glucose_mgdl": np.where(label == 1, rng.normal(260, 70, n), rng.normal(92, 12, n)).round(0),
        "hba1c_pct": np.where(label == 1, rng.normal(9.5, 2.0, n), rng.normal(5.2, 0.4, n)).round(1),
        "autoantibody_count": rng.binomial(4, np.where(label == 1, 0.6, 0.03)),
        "label": label,
    })
    df["glucose_mgdl"] = df["glucose_mgdl"].clip(40, 800)
    df["hba1c_pct"] = df["hba1c_pct"].clip(3.5, 18.0)
    # Realistic missingness so the imputer in the pipeline is actually exercised.
    mask = rng.random(n) < 0.35
    df.loc[mask, "hba1c_pct"] = np.nan
    df.loc[rng.random(n) < 0.80, "autoantibody_count"] = np.nan
    return df


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=1200)
    ap.add_argument("--seed", type=int, default=20261027)
    ap.add_argument("--out", default=str(HERE / "data" / "synthetic_demo.csv"))
    args = ap.parse_args()

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    df = generate(args.n, args.seed)
    df.to_csv(out, index=False)

    manifest = {
        "dataset_label": "synthetic_demo",
        "synthetic": True,
        "do_not_use_for_research_claims": True,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "n_rows": int(len(df)),
        "seed": args.seed,
        "target": "label",
        "target_meaning": "arbitrary binary class invented by the generator",
        "provenance": "generated by ml/make_synthetic.py; no human subject contributed to it",
        "warning": (
            "Any metric computed from this file describes the generator, not type 1 "
            "diabetes. Do not report these numbers in the manuscript."
        ),
    }
    out.with_suffix(".manifest.json").write_text(json.dumps(manifest, indent=2))
    print(f"wrote {out} ({len(df)} rows) and its manifest")


if __name__ == "__main__":
    main()
